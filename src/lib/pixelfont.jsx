export const GLYPH_W = 5
export const GLYPH_H = 7

/** Pixel rects for one line of text, in glyph-cell units. */
export function textRects(text, { gap = 1 } = {}) {
  const rects = []
  let x = 0
  for (const raw of text.toUpperCase()) {
    const g = G[raw] || G[' ']
    for (let r = 0; r < GLYPH_H; r++) {
      for (let c = 0; c < GLYPH_W; c++) {
        if (g[r][c] === '1') rects.push([x + c, r])
      }
    }
    x += GLYPH_W + gap
  }
  return { rects, width: Math.max(0, x - gap) }
}

/**
 * Pixel-type as SVG. `lines` is [{ text, fill }]; `px` is the pixel size.
 */
export function PixelText({ lines, px = 4, gap = 1, lineGap = 3, className, style, align = 'left' }) {
  const laid = lines.map((l) => ({ ...l, ...textRects(l.text, { gap }) }))
  const width = Math.max(...laid.map((l) => l.width))
  const height = laid.length * GLYPH_H + (laid.length - 1) * lineGap

  return (
    <svg
      className={className}
      style={style}
      width={width * px}
      height={height * px}
      viewBox={`0 0 ${width} ${height}`}
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      {laid.map((line, li) => {
        const dx = align === 'center' ? Math.round((width - line.width) / 2) : 0
        const dy = li * (GLYPH_H + lineGap)
        return (
          <g key={li} fill={line.fill || 'currentColor'}>
            {line.rects.map(([x, y], i) => (
              <rect key={i} x={x + dx} y={y + dy} width={1} height={1} />
            ))}
          </g>
        )
      })}
    </svg>
  )
}
